/*
 * XamlProbeLifetimeTests.cpp - M10 gate 2.4 verification harness.
 *
 * Task 2.4 requires proving two things about the C++/CX probe component:
 *
 *   1. Activation returns a valid HRESULT, and a failure inside activation is
 *      reported as a failure code rather than terminating the process.
 *   2. Reference counting and destruction are correct across the success path and
 *      across every failure path.
 *
 * Why this is a separate host program rather than a device test. The shipping
 * component is ARM32, and an ARM32 image cannot execute on this x64 development
 * host. The language-level behaviour under test is architecture independent, so it
 * is exercised here against an x64 build of the same source, and the ARM32 build is
 * carried on the device as part of task 2.6. What this harness proves is the
 * activation contract and the lifetime contract; it deliberately does not claim to
 * prove device behaviour.
 *
 * The harness loads the component by path and resolves DllGetActivationFactory
 * through GetProcAddress rather than linking against the component. That keeps the
 * test honest about the same surface a real host uses, and means a component that
 * forgets to export the entry point fails the test rather than being linked in
 * implicitly.
 *
 * Expected results are asserted and reported individually. The harness prints one
 * line per check and exits non-zero if any fails, so a partially passing run is
 * visible rather than summarized as success.
 */

#include <windows.h>

#include <roapi.h>
#include <winerror.h>

// The XAML headers pulled in by XamlProbe.h declare a function-like macro named
// GetCurrentTime that collides with the Windows declaration, producing C4002. The
// macro is undefined before those headers are parsed so the Windows declaration is
// the one that survives; the harness uses none of the XAML declarations.
//
// ABI projection of IXamlProbe, generated by midlrt from XamlProbe.idl into the
// build output. The macro name is the consumer-facing spelling: the generated
// header defines __x_ABI_CWebKitProbe_CIXamlProbe as ABI::WebKitProbe::IXamlProbe.
// Using the macro rather than hard-coding a UUID means the harness cannot pass if
// the generated metadata and the harness disagree about which interface is the
// default one.
#ifdef GetCurrentTime
#undef GetCurrentTime
#endif
#include <XamlProbe.h>

#include <cstdio>
#include <cstring>
#include <string>

namespace {

#ifdef XAML_PROBE_LIFETIME_LIBRARY
extern "C" void XamlProbeRecordStage(int);
#else
void XamlProbeRecordStage(int) { }
#endif

// Fully-qualified runtime class name the probe IDL declares. Must match
// RuntimeClass_WebKitProbe_XamlProbe in the generated metadata.
constexpr wchar_t kProbeClassName[] = L"WebKitProbe.XamlProbe";

// A class name the component must refuse. The probe's DllGetActivationFactory
// answers CLASS_E_CLASSNOTAVAILABLE for anything but its own class, so this
// exercises the rejection path without depending on another registered class.
constexpr wchar_t kUnknownClassName[] = L"WebKitProbe.NoSuchClass";

// Fixed value XamlProbe::get_ProbeId returns, used to prove the object reached is
// the probe rather than an unrelated registration.
constexpr unsigned int kExpectedProbeId = 0x0001U;

// Accounting for the process-wide pass/fail tally. Reported checks are counted
// separately from failures so the summary cannot hide a skipped assertion.
int gChecksRun = 0;
int gChecksFailed = 0;

void ReportCheck(const char* name, bool passed, const char* detail)
{
    ++gChecksRun;
    if (!passed)
        ++gChecksFailed;
    char line[256];
    std::snprintf(line, sizeof(line), "  [%s] %s%s%s\n", passed ? "PASS" : "FAIL", name,
        detail && *detail ? " - " : "", detail ? detail : "");
    std::printf("%s", line);
    OutputDebugStringA(line);
}

// Formats an HRESULT as 0x%08X so failures identify the exact code rather than
// requiring the reader to look it up.
void FormatHResult(HRESULT value, char* buffer, size_t size)
{
    std::snprintf(buffer, size, "0x%08X", static_cast<unsigned int>(value));
}

// Loads the component and resolves its activation entry point.
//
// LOAD_WITH_ALTERED_SEARCH_PATH is used so the component's own imports resolve
// against the directory it was loaded from, which is what a packaged host gets.
// The path arrives as UTF-8 from argv and is widened here, because the harness
// deliberately avoids depending on the console code page.
using GetActivationFactoryFn = HRESULT(STDMETHODCALLTYPE*)(HSTRING, IActivationFactory**);
using DllCanUnloadNowFn = HRESULT(STDMETHODCALLTYPE*)();

// Widens a UTF-8 path from argv into UTF-16. The harness converts explicitly
// rather than depending on the console code page, so the component path is the
// same regardless of how the shell encodes it.
std::wstring WidenUtf8(const char* narrow)
{
    if (!narrow || !*narrow)
        return std::wstring();

    const int required = MultiByteToWideChar(CP_UTF8, 0, narrow, -1, nullptr, 0);
    if (required <= 1)
        return std::wstring();

    std::wstring wide(static_cast<size_t>(required - 1), L'\0');
    // The buffer is written in place, so the const-qualification that .data()
    // reports is dropped deliberately here and nowhere else.
    MultiByteToWideChar(CP_UTF8, 0, narrow, -1, &wide[0], required);
    return wide;
}

HMODULE LoadComponent(const char* componentPath, GetActivationFactoryFn* outEntry)
{
    const std::wstring wide = WidenUtf8(componentPath);
    if (wide.empty()) {
        std::printf("  component path is empty or not valid UTF-8\n");
        return nullptr;
    }

    HMODULE module = LoadLibraryExW(wide.c_str(), nullptr, LOAD_WITH_ALTERED_SEARCH_PATH);
    if (!module) {
        char detail[64];
        FormatHResult(HRESULT_FROM_WIN32(GetLastError()), detail, sizeof(detail));
        std::printf("  LoadLibraryEx failed for %s (%s)\n", componentPath, detail);
        return nullptr;
    }

    auto entry = reinterpret_cast<GetActivationFactoryFn>(
        GetProcAddress(module, "DllGetActivationFactory"));
    if (!entry) {
        std::printf("  component does not export DllGetActivationFactory\n");
        FreeLibrary(module);
        return nullptr;
    }

    if (outEntry)
        *outEntry = entry;
    return module;
}

// Test 1: the component exports a working activation entry point, and reports a
// failure HRESULT rather than terminating when asked for a class it does not
// serve.
void TestActivationRejection(HMODULE module, GetActivationFactoryFn entry)
{
    std::printf("activation rejection\n");

    HSTRING requested = nullptr;
    HRESULT created = WindowsCreateString(kUnknownClassName,
        static_cast<UINT32>(wcslen(kUnknownClassName)), &requested);
    if (FAILED(created)) {
        ReportCheck("WindowsCreateString for unknown class", false, "could not build HSTRING");
        return;
    }

    IActivationFactory* factory = nullptr;
    HRESULT result = entry(requested, &factory);

    char detail[64];
    FormatHResult(result, detail, sizeof(detail));

    // CLASS_E_CLASSNOTAVAILABLE is the documented answer for an unregistered class.
    // What matters for the gate is that it is a failure code at all: a component
    // that crashed or returned S_OK with a null factory would both be wrong.
    bool rejected = FAILED(result) && result != E_OUTOFMEMORY;
    ReportCheck("unknown class rejected with a failure HRESULT", rejected, detail);

    // A failed activation must not hand back a factory the caller could then use.
    if (factory) {
        ReportCheck("no factory leaked on the rejection path", false,
            SUCCEEDED(result) ? "factory returned for an unknown class" : "factory returned on failure");
        factory->Release();
    }
    else {
        ReportCheck("no factory leaked on the rejection path", true, nullptr);
    }

    // A null output pointer must be refused rather than dereferenced. This is the
    // cheapest way to distinguish a component that validates its inputs from one
    // that only works when the caller behaves.
    result = entry(requested, nullptr);
    FormatHResult(result, detail, sizeof(detail));
    ReportCheck("null factory out-parameter refused", FAILED(result), detail);

    WindowsDeleteString(requested);
}

// Test 2: the success path returns a valid HRESULT, the activated object exposes
// the declared default interface, and its reported identity is the probe's.
void TestActivationSuccess(HMODULE module, GetActivationFactoryFn entry)
{
    std::printf("activation success and default interface\n");

    HSTRING requested = nullptr;
    HRESULT result = WindowsCreateString(kProbeClassName,
        static_cast<UINT32>(wcslen(kProbeClassName)), &requested);
    if (FAILED(result)) {
        ReportCheck("WindowsCreateString for probe class", false, "could not build HSTRING");
        return;
    }

    IActivationFactory* factory = nullptr;
    result = entry(requested, &factory);

    char detail[64];
    FormatHResult(result, detail, sizeof(detail));
    ReportCheck("activation returns S_OK", result == S_OK, detail);

    if (FAILED(result) || !factory) {
        ReportCheck("factory obtained", false, "no factory to test against");
        WindowsDeleteString(requested);
        return;
    }

    // The factory must name the class it serves. If this is wrong, an app that
    // activates by name would silently get some other registered class.
    HSTRING reportedName = nullptr;
    result = factory->GetRuntimeClassName(&reportedName);
    FormatHResult(result, detail, sizeof(detail));
    bool nameOk = SUCCEEDED(result);
    if (nameOk) {
        UINT32 length = 0;
        const wchar_t* buffer = WindowsGetStringRawBuffer(reportedName, &length);
        nameOk = buffer && length == wcslen(kProbeClassName)
            && wcsncmp(buffer, kProbeClassName, length) == 0;
        std::snprintf(detail, sizeof(detail), "0x%08X", static_cast<unsigned int>(result));
    }
    ReportCheck("factory reports the probe runtime class name", nameOk, detail);
    if (reportedName)
        WindowsDeleteString(reportedName);

    // Trust level must be reported as a valid enum value. BaseTrust is 0 and
    // PartialTrust is 1; anything else means the object is not honouring the
    // contract the IDL declared.
    TrustLevel level = BaseTrust;
    result = factory->GetTrustLevel(&level);
    FormatHResult(result, detail, sizeof(detail));
    bool levelOk = SUCCEEDED(result) && (level == BaseTrust || level == PartialTrust);
    ReportCheck("factory reports a valid trust level", levelOk, detail);

    // Activating the instance is the path whose HRESULT the gate names directly.
    IInspectable* instance = nullptr;
    result = factory->ActivateInstance(&instance);
    FormatHResult(result, detail, sizeof(detail));

    bool activated = SUCCEEDED(result);
    if (activated)
        activated = instance != nullptr;
    ReportCheck("ActivateInstance returns success with an instance", activated, detail);

    if (!activated) {
        if (instance)
            instance->Release();
        factory->Release();
        WindowsDeleteString(requested);
        return;
    }

    // QueryInterface for the declared default interface. This is the check that
    // the metadata, the CX declaration and the object agree; a mismatch here is
    // what makes a control unusable from XAML markup.
    __x_ABI_CWebKitProbe_CIXamlProbe* probeInterface = nullptr;
    HRESULT qi = instance->QueryInterface(__uuidof(__x_ABI_CWebKitProbe_CIXamlProbe),
        reinterpret_cast<void**>(&probeInterface));
    FormatHResult(qi, detail, sizeof(detail));
    bool qiOk = SUCCEEDED(qi) && probeInterface != nullptr;
    if (qiOk) {
        UINT32 probeId = 0;
        HRESULT got = probeInterface->get_ProbeId(&probeId);
        FormatHResult(got, detail, sizeof(detail));
        qiOk = SUCCEEDED(got) && probeId == kExpectedProbeId;
        std::snprintf(detail, sizeof(detail), "id=0x%X", probeId);
    }
    ReportCheck("default interface resolves and reports the probe identity", qiOk, detail);

    if (probeInterface)
        probeInterface->Release();
    instance->Release();
    factory->Release();
    WindowsDeleteString(requested);
}

// Test 3: reference counting is exact across repeated activation.
//
// A C++/CX ref class is refcounted by the CX runtime. Creating many instances and
// releasing them in a loop catches an object that leaks a reference (detectable as
// a failure to destroy) or over-releases (detectable as a crash or an invalid
// refcount during the next iteration).
void TestRepeatedActivationLifetime(HMODULE module, GetActivationFactoryFn entry)
{
    std::printf("repeated activation and destruction\n");

    // Iteration count is deliberately larger than any incidental reference the
    // runtime keeps, so a single leaked reference per instance would show up.
    constexpr int kIterations = 256;

    HSTRING requested = nullptr;
    HRESULT result = WindowsCreateString(kProbeClassName,
        static_cast<UINT32>(wcslen(kProbeClassName)), &requested);
    if (FAILED(result)) {
        ReportCheck("WindowsCreateString for probe class", false, "could not build HSTRING");
        return;
    }

    IActivationFactory* factory = nullptr;
    result = entry(requested, &factory);
    if (FAILED(result) || !factory) {
        ReportCheck("factory obtained for lifetime loop", false, "activation failed");
        WindowsDeleteString(requested);
        return;
    }

    int activatedCount = 0;
    int failureCount = 0;
    HRESULT firstFailure = S_OK;

    for (int i = 0; i < kIterations; ++i) {
        IInspectable* instance = nullptr;
        HRESULT activateResult = factory->ActivateInstance(&instance);
        if (FAILED(activateResult) || !instance) {
            if (firstFailure == S_OK)
                firstFailure = activateResult;
            ++failureCount;
            continue;
        }

        ++activatedCount;

        // Exercise the reference count the way a consumer would: take an extra
        // reference through the interface, then drop both. A component that
        // miscounts surfaces here rather than at process teardown.
        __x_ABI_CWebKitProbe_CIXamlProbe* probeInterface = nullptr;
        if (SUCCEEDED(instance->QueryInterface(__uuidof(__x_ABI_CWebKitProbe_CIXamlProbe),
                reinterpret_cast<void**>(&probeInterface)))
            && probeInterface) {
            probeInterface->Release();
        }
        instance->Release();
    }

    char detail[80];
    std::snprintf(detail, sizeof(detail), "%d/%d activated", activatedCount, kIterations);
    ReportCheck("every activation in the loop succeeded", failureCount == 0, detail);

    if (failureCount && firstFailure != S_OK) {
        char code[32];
        FormatHResult(firstFailure, code, sizeof(code));
        std::printf("        first failure: %s\n", code);
    }

    // Releasing the factory last is the required order: it is the only reference
    // keeping the component's activation state alive during the loop.
    factory->Release();
    WindowsDeleteString(requested);
}

// Test 4: interleaved activation and rejection must not corrupt state. The
// rejected request runs between successful ones, so a component that mishandles
// the rejection path would corrupt the next activation.
void TestInterleavedRejection(HMODULE module, GetActivationFactoryFn entry)
{
    std::printf("interleaved success and rejection\n");

    HSTRING probeName = nullptr;
    HSTRING unknownName = nullptr;
    if (FAILED(WindowsCreateString(kProbeClassName,
            static_cast<UINT32>(wcslen(kProbeClassName)), &probeName))
        || FAILED(WindowsCreateString(kUnknownClassName,
            static_cast<UINT32>(wcslen(kUnknownClassName)), &unknownName))) {
        ReportCheck("HSTRINGs built for interleaved test", false, "could not build HSTRINGs");
        return;
    }

    int successfulActivations = 0;
    bool rejectionsStayedRejections = true;

    for (int i = 0; i < 32; ++i) {
        IActivationFactory* rejected = nullptr;
        HRESULT rejectResult = entry(unknownName, &rejected);
        if (rejectResult == S_OK) {
            rejectionsStayedRejections = false;
        }
        if (rejected)
            rejected->Release();

        IActivationFactory* factory = nullptr;
        HRESULT result = entry(probeName, &factory);
        if (FAILED(result) || !factory) {
            if (factory)
                factory->Release();
            continue;
        }

        IInspectable* instance = nullptr;
        if (SUCCEEDED(factory->ActivateInstance(&instance)) && instance) {
            ++successfulActivations;
            instance->Release();
        }
        factory->Release();
    }

    char detail[80];
    std::snprintf(detail, sizeof(detail), "%d/32 activations after rejection", successfulActivations);
    ReportCheck("activations still succeed after interleaved rejections",
        successfulActivations == 32, detail);
    ReportCheck("rejections stayed rejections across the loop",
        rejectionsStayedRejections, nullptr);

    WindowsDeleteString(probeName);
    WindowsDeleteString(unknownName);
}

} // namespace

int RunXamlProbeLifetimeChecks(HMODULE module, const char* componentDescription);

#ifndef XAML_PROBE_LIFETIME_LIBRARY
int __cdecl main(int argc, char** argv)
{
    // Keep each check visible even if a malformed component terminates the host
    // during LoadLibraryExW; buffered stdout would otherwise hide the last step.
    std::setvbuf(stdout, nullptr, _IONBF, 0);

    if (argc < 2) {
        std::printf("usage: %s <path-to-component.dll>\n", argv[0]);
        return 2;
    }

    const char* componentPath = argv[1];
    std::printf("M10 gate 2.4 activation and lifetime verification\n");
    std::printf("component: %s\n\n", componentPath);

    const HRESULT roInit = RoInitialize(RO_INIT_MULTITHREADED);
    if (FAILED(roInit)) {
        char detail[64];
        FormatHResult(roInit, detail, sizeof(detail));
        std::printf("RESULT: FAIL - RoInitialize failed (%s)\n", detail);
        return 1;
    }

    HMODULE module = LoadComponent(componentPath, nullptr);
    if (!module) {
        std::printf("\nRESULT: FAIL - component could not be loaded or lacks the activation entry point\n");
        RoUninitialize();
        return 1;
    }

    const int result = RunXamlProbeLifetimeChecks(module, componentPath);
    RoUninitialize();
    return result;
}
#endif

int RunXamlProbeLifetimeChecks(HMODULE module, const char* componentDescription)
{
    std::printf("M10 gate 2.4 activation and lifetime verification\n");
    std::printf("component: %s\n\n", componentDescription);

    if (!module) {
        std::printf("RESULT: FAIL - component could not be loaded\n");
        return 1;
    }

    auto entry = reinterpret_cast<GetActivationFactoryFn>(
        GetProcAddress(module, "DllGetActivationFactory"));
    if (!entry) {
        std::printf("RESULT: FAIL - component lacks DllGetActivationFactory\n");
        FreeLibrary(module);
        return 1;
    }
    XamlProbeRecordStage(200);

    TestActivationRejection(module, entry);
    XamlProbeRecordStage(201);
    TestActivationSuccess(module, entry);
    XamlProbeRecordStage(202);
    TestRepeatedActivationLifetime(module, entry);
    XamlProbeRecordStage(203);
    TestInterleavedRejection(module, entry);
    XamlProbeRecordStage(204);

    // The component deliberately reports S_FALSE from DllCanUnloadNow while its
    // activation state is resident. Forcing FreeLibrary here violates that
    // contract and crashes the ARM32 XAML runtime after otherwise successful
    // teardown. The process owns the module for the remainder of this test, and
    // the OS unloads it during process exit.
    XamlProbeRecordStage(205);
    auto canUnload = reinterpret_cast<DllCanUnloadNowFn>(
        GetProcAddress(module, "DllCanUnloadNow"));
    HRESULT unloadResult = canUnload ? canUnload() : E_NOINTERFACE;
    char unloadDetail[64];
    FormatHResult(unloadResult, unloadDetail, sizeof(unloadDetail));
    ReportCheck("component retains its resident activation state", unloadResult == S_FALSE, unloadDetail);
    XamlProbeRecordStage(206);
    // The CoreApplication event loop may remain owned by the platform after the
    // view requests exit. Write the aggregate result before returning so device
    // evidence does not depend on the process reaching its normal entrypoint.
    XamlProbeRecordStage(gChecksFailed ? 1000 + gChecksFailed : 0);
    std::printf("\n%zu checks, %d failed\n",
        static_cast<size_t>(gChecksRun), gChecksFailed);
    std::printf("RESULT: %s\n", gChecksFailed == 0 ? "PASS" : "FAIL");
    return gChecksFailed == 0 ? 0 : 1;
}
